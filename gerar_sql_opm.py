sql = "-- Atualização dos dados de Organismos de Políticas para Mulheres (OPM)\n\n"

for line in data.strip().split('\n'):
    parts = line.split('\t')
    if len(parts) == 3:
        municipio = parts[0].strip()
        possui = parts[1].strip()
        tipologia = parts[2].strip()
        
        # Mapeamento do "Possui" para 'SIM' ou 'NAO'
        opm_possui = 'SIM' if possui.lower() == 'sim' else 'NAO'
        
        # Mapeamento da "Tipologia" (remove traços e formata se existir)
        opm_orgaotipo = '' if tipologia == '-' else tipologia
        
        # Escapando as aspas simples caso o município contenha, ex: D'Alcântara
        municipio_escaped = municipio.replace("'", "''")
        
        sql += f"UPDATE municipios SET opm_possui = '{opm_possui}', opm_orgaotipo = '{opm_orgaotipo}' WHERE municipio = '{municipio_escaped}';\n"

with open('atualizar_opm.sql', 'w', encoding='utf-8') as f:
    f.write(sql)

